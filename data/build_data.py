def idx(f):
    d={}
    for line in open(f):
        line=line.rstrip('\n')
        if not line.strip(): continue
        n,w=line.split('\t')
        ws=[x.strip() for x in w.split('،') if x.strip()]
        d.setdefault(int(n),[])
        for x in ws:
            if x not in d[int(n)]: d[int(n)].append(x)
    return d
